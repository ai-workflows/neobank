/**
 * Neobank Demo Orchestrator
 *
 * Manages parallel Claude Code workers building the neobank app.
 * Uses GitHub issues as task queue and Panes MCP for terminal I/O.
 *
 * Flow:
 * 1. Create GitHub issues from project-plan.json
 * 2. Spin up worker VMs via Panes API
 * 3. Assign tasks to idle workers
 * 4. Monitor PRs, auto-merge, reassign
 */

import { execSync } from 'child_process';
import { readFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Configuration
const PANES_API_URL = process.env.PANES_API_URL || 'https://staging.a9s.dev';
const PANES_API_TOKEN = process.env.PANES_API_TOKEN || '';
const REPO = process.env.REPO || 'ai-workflows/neobank';
const POLL_INTERVAL_MS = 15_000; // 15 seconds
const MAX_WORKERS = parseInt(process.env.MAX_WORKERS || '10', 10);

interface Task {
  id: number;
  title: string;
  team: string;
  priority: number;
  spec: string;
  files: string[];
}

interface Worker {
  id: string;
  machineId: string;
  sessionId: string;
  status: 'idle' | 'working' | 'reviewing';
  currentIssue?: number;
  currentBranch?: string;
}

interface ProjectPlan {
  name: string;
  repo: string;
  teams: string[];
  tasks: Task[];
}

// State
const workers: Worker[] = [];
let running = true;

// ─── Helpers ───────────────────────────────────────────────

function gh(args: string): string {
  try {
    return execSync(`gh ${args}`, {
      encoding: 'utf-8',
      timeout: 30_000,
      env: { ...process.env, GH_REPO: REPO },
    }).trim();
  } catch (e: any) {
    console.error(`[gh] Failed: gh ${args}`);
    console.error(e.stderr || e.message);
    return '';
  }
}

async function panesApi(method: string, path: string, body?: unknown): Promise<any> {
  const res = await fetch(`${PANES_API_URL}/api${path}`, {
    method,
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${PANES_API_TOKEN}`,
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`Panes API ${method} ${path}: ${res.status} ${text}`);
  }
  return res.json();
}

function log(msg: string) {
  const ts = new Date().toISOString().slice(11, 19);
  console.log(`[${ts}] ${msg}`);
}

// ─── Phase 1: Create GitHub Issues ─────────────────────────

function createIssues(plan: ProjectPlan) {
  log(`Creating ${plan.tasks.length} issues in ${REPO}...`);

  for (const task of plan.tasks) {
    const body = [
      `## Task Spec`,
      '',
      task.spec,
      '',
      `## Files`,
      ...task.files.map((f) => `- \`${f}\``),
      '',
      `## Notes`,
      `- Priority: ${task.priority}`,
      `- Team: ${task.team}`,
      `- Auto-generated by orchestrator`,
    ].join('\n');

    const result = gh(
      `issue create --title "${task.title}" --label "team:${task.team}" --label "status:open" --label "priority:${task.priority}" --body "${body.replace(/"/g, '\\"')}"`
    );
    log(`  Created: #${result.match(/#?(\d+)/)?.[1] || '?'} - ${task.title}`);
  }

  log(`All ${plan.tasks.length} issues created.`);
}

// ─── Phase 2: Worker Management ────────────────────────────

async function createWorker(index: number): Promise<Worker> {
  log(`Creating worker ${index}...`);

  // Create VM via Panes API
  const machine = await panesApi('POST', '/machines', {
    name: `worker-${index}`,
    template: 'panes-vm',
    compute_size: 'standard',
    env: {
      PANES_API_URL,
      PANES_API_TOKEN,
    },
  });

  log(`  Machine ${machine.machine_id} created, waiting for ready...`);

  // Wait for machine to be running
  let status = 'creating';
  while (status !== 'running') {
    await new Promise((r) => setTimeout(r, 5000));
    const m = await panesApi('GET', `/machines/${machine.machine_id}`);
    status = m.status;
    log(`  Machine ${machine.machine_id}: ${status}`);
  }

  // Create a terminal session on the machine
  const session = await panesApi('POST', `/machines/${machine.machine_id}/sessions/terminal`, {
    label: `Worker ${index}`,
  });

  log(`  Worker ${index} ready: machine=${machine.machine_id} session=${session.id}`);

  return {
    id: `worker-${index}`,
    machineId: machine.machine_id,
    sessionId: session.id,
    status: 'idle',
  };
}

async function sendToWorker(worker: Worker, text: string) {
  await panesApi('POST', `/sessions/${worker.sessionId}/input`, {
    text,
    literal: true,
  });
}

async function sendEnter(worker: Worker) {
  await panesApi('POST', `/sessions/${worker.sessionId}/input`, {
    text: '\n',
    literal: true,
  });
}

async function getWorkerOutput(worker: Worker, lines = 50): Promise<string> {
  const result = await panesApi('GET', `/sessions/${worker.sessionId}/output?lines=${lines}`);
  return result.output || '';
}

// ─── Phase 3: Task Assignment ──────────────────────────────

function getOpenIssues(): Array<{ number: number; title: string; team: string }> {
  const raw = gh('issue list --label "status:open" --json number,title,labels --limit 100');
  if (!raw) return [];

  try {
    const issues = JSON.parse(raw);
    return issues.map((issue: any) => ({
      number: issue.number,
      title: issue.title,
      team:
        issue.labels
          ?.find((l: any) => l.name.startsWith('team:'))
          ?.name.replace('team:', '') || 'unknown',
    }));
  } catch {
    return [];
  }
}

function getPendingPRs(): Array<{ number: number; title: string; headRefName: string }> {
  const raw = gh('pr list --state open --json number,title,headRefName --limit 100');
  if (!raw) return [];
  try {
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

async function assignTask(worker: Worker, issue: { number: number; title: string }) {
  log(`Assigning issue #${issue.number} (${issue.title}) to ${worker.id}`);

  // Get full issue body
  const body = gh(`issue view ${issue.number} --json body -q .body`);

  // Update labels
  gh(`issue edit ${issue.number} --add-label "status:assigned" --remove-label "status:open"`);

  // Branch name
  const branch = `worker/${worker.id}/issue-${issue.number}`;
  worker.currentIssue = issue.number;
  worker.currentBranch = branch;
  worker.status = 'working';

  // Send task to worker's Claude Code session
  const prompt = [
    `Work on issue #${issue.number}: ${issue.title}`,
    ``,
    `${body}`,
    ``,
    `Instructions:`,
    `1. Create a new branch: git checkout -b ${branch}`,
    `2. Implement the changes described above`,
    `3. Commit your changes with a descriptive message`,
    `4. Push: git push -u origin ${branch}`,
    `5. Create a PR: gh pr create --title "${issue.title}" --body "Closes #${issue.number}" --label "status:review"`,
    `6. Say "DONE" when finished`,
  ].join('\n');

  await sendToWorker(worker, prompt);
  await sendEnter(worker);
}

// ─── Phase 4: PR Management ───────────────────────────────

async function reviewAndMergePRs() {
  const prs = getPendingPRs();

  for (const pr of prs) {
    log(`Auto-merging PR #${pr.number}: ${pr.title}`);

    // Merge the PR
    gh(`pr merge ${pr.number} --merge --delete-branch`);

    // Find the worker that owns this PR and mark idle
    const worker = workers.find((w) => w.currentBranch === pr.headRefName);
    if (worker) {
      worker.status = 'idle';
      worker.currentIssue = undefined;
      worker.currentBranch = undefined;
      log(`  ${worker.id} is now idle`);
    }
  }
}

// ─── Main Loop ─────────────────────────────────────────────

async function mainLoop() {
  while (running) {
    try {
      // 1. Check for PRs to merge
      await reviewAndMergePRs();

      // 2. Find idle workers and assign tasks
      const idleWorkers = workers.filter((w) => w.status === 'idle');
      if (idleWorkers.length > 0) {
        const openIssues = getOpenIssues();

        for (const worker of idleWorkers) {
          if (openIssues.length === 0) break;
          const issue = openIssues.shift()!;
          await assignTask(worker, issue);
        }
      }

      // 3. Status report
      const working = workers.filter((w) => w.status === 'working').length;
      const idle = workers.filter((w) => w.status === 'idle').length;
      const openIssues = getOpenIssues();
      const prs = getPendingPRs();
      log(`Status: ${working} working, ${idle} idle, ${openIssues.length} issues open, ${prs.length} PRs pending`);
    } catch (err) {
      log(`Error in main loop: ${err}`);
    }

    await new Promise((r) => setTimeout(r, POLL_INTERVAL_MS));
  }
}

// ─── Entry Point ───────────────────────────────────────────

async function main() {
  const args = process.argv.slice(2);
  const command = args[0] || 'run';

  if (!PANES_API_TOKEN) {
    console.error('PANES_API_TOKEN is required');
    process.exit(1);
  }

  const plan: ProjectPlan = JSON.parse(
    readFileSync(join(__dirname, 'project-plan.json'), 'utf-8')
  );

  switch (command) {
    case 'create-issues': {
      createIssues(plan);
      break;
    }

    case 'setup-workers': {
      const count = parseInt(args[1] || String(MAX_WORKERS), 10);
      log(`Setting up ${count} workers...`);
      for (let i = 1; i <= count; i++) {
        const worker = await createWorker(i);
        workers.push(worker);
      }
      log(`All ${count} workers ready.`);
      // Print worker info
      for (const w of workers) {
        console.log(`  ${w.id}: machine=${w.machineId} session=${w.sessionId}`);
      }
      break;
    }

    case 'run': {
      log('Starting orchestrator...');

      // Create issues if none exist
      const existing = getOpenIssues();
      if (existing.length === 0) {
        createIssues(plan);
      } else {
        log(`Found ${existing.length} existing open issues, skipping creation.`);
      }

      // Setup workers
      const count = parseInt(args[1] || String(MAX_WORKERS), 10);
      log(`Setting up ${count} workers...`);
      for (let i = 1; i <= count; i++) {
        const worker = await createWorker(i);
        workers.push(worker);
      }

      // Start main loop
      log('Starting main loop...');
      await mainLoop();
      break;
    }

    default:
      console.log('Usage: orchestrator.ts [create-issues|setup-workers|run] [worker-count]');
  }
}

// Graceful shutdown
process.on('SIGINT', () => {
  log('Shutting down...');
  running = false;
});

main().catch((err) => {
  console.error('Fatal:', err);
  process.exit(1);
});
